// Built-in database of Singapore hawker dishes, kueh, and kopitiam drinks.
// Values are typical HPB-style figures for a standard serving of the whole
// dish, so "1 serving" = one plate/bowl/piece as sold. Entered per serving
// and converted to per-100g here to match the COMMON_FOODS shape.
// Names lead with the local name (what people search) followed by an
// English description in parentheses. Values audited 12 Jul 2026: every
// entry's kcal agrees with its 4/4/9 macro arithmetic and with published
// per-serving reference figures. Fibre (g/serving) and sodium (mg/serving)
// added 12 Jul 2026 — sodium especially varies stall to stall; treat as
// typical mid-range figures.

const D = (name, grams, kcal, protein, carbs, fat, fibre = null, sodium = null) => ({
  name,
  brand: 'Local',
  serving: `${grams} g`,
  per100: {
    kcal: r1((kcal * 100) / grams),
    protein: r1((protein * 100) / grams),
    carbs: r1((carbs * 100) / grams),
    fat: r1((fat * 100) / grams),
    fibre: fibre == null ? null : r1((fibre * 100) / grams),
    sodium: sodium == null ? null : Math.round((sodium * 100) / grams),
  },
});

